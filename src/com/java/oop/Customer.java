package com.java.oop;

public class Customer {
    public int id;
    public String name;
    public String email;
    public String phoneNo;
    public byte age;

    public Customer(int id, String name, String email, String phoneNo, byte age) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.phoneNo = phoneNo;
        this.age = age;
    }
}
